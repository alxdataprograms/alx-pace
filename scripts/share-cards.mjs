async function loadPlaywright() {
  const candidates = [process.env.PLAYWRIGHT_MODULE, 'playwright'].filter(Boolean)
  const require = createRequire(import.meta.url)
  for (const c of candidates) {
    try {
      return require(c)
    } catch {
      /* try the next */
    }
  }
  throw new Error(
    'Playwright not found. Install it, or set PLAYWRIGHT_MODULE to its path (and CHROMIUM_PATH to a browser binary).',
  )
}

// The page.evaluate callbacks below run in Chromium, where `document` exists.
/* global document */
async function renderImages(cards) {
  const { chromium } = await loadPlaywright()
  const browser = await chromium.launch(
    process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {},
  )
  const fontsDir = join(ROOT, 'scripts/share-cards/fonts')
  try {
    const page = await browser.newPage({ viewport: { width: IMAGE_WIDTH, height: IMAGE_HEIGHT } })
    for (const { card, out } of cards) {
      const tmp = join(tmpdir(), 'alx-pace-share-card.html')
      writeFileSync(tmp, cardImageHtml(card, fontsDir))
      await page.goto(pathToFileURL(tmp).href)
      await page.evaluate(() => document.fonts.ready)
      // Never ship a card in a fallback font: fail loudly instead.
      const ok = await page.evaluate(() =>
        [400, 600, 700].every((w) => document.fonts.check(`${w} 20px Poppins`)),
      )
      if (!ok) throw new Error(`Poppins did not load for ${out}`)
      mkdirSync(dirname(out), { recursive: true })
      await page.screenshot({ path: out, type: 'png' })
      console.log(`  wrote ${out.replace(ROOT, '')}`)
    }
  } finally {
    await browser.close()
  }
}

async function main() {
  for (const card of SHARE_CARDS) {
    const out = join(ROOT, 'public/share', card.id, 'index.html')
    mkdirSync(dirname(out), { recursive: true })
    writeFileSync(out, sharePageHtml(card))
    console.log(`  wrote ${out.replace(ROOT, '')}`)
  }
  if (process.argv.includes('--images')) {
    await renderImages([
      { card: ROOT_CARD, out: join(ROOT, 'public/og-image.png') },
      ...SHARE_CARDS.map((card) => ({
        card,
        out: join(ROOT, 'public/share', card.id, 'og-image.png'),
      })),
    ])
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((err) => {
    console.error(err.message)
    process.exit(1)
  })
}
