#!/usr/bin/env node
/**
 * One link-preview card per program — the static pages LinkedIn, WhatsApp, X
 * and Slack read, and the 1200×627 images on them.
 *
 * WHY STATIC PAGES
 * Link crawlers read Open Graph tags from the HTML they are served and never
 * run JavaScript, so a single-page app has exactly one card: whatever
 * index.html says. A Graphic Design learner's milestone post would preview as
 * a Data Analytics tracker. Each program therefore gets a tiny page of its own
 * at share/<id>/ carrying that program's tags, which sends a person straight
 * on to the app. The milestone post links to the learner's program page.
 *
 * WHAT THIS WRITES (all committed — Pages serves public/ as-is)
 *   public/share/<id>/index.html   per-program card + redirect, always
 *   public/share/<id>/og-image.png per-program image       } with --images
 *   public/og-image.png            program-neutral image  } (needs Playwright)
 *
 * The page HTML is a pure function of the data below, and
 * src/lib/sharePages.test.js asserts the committed files still match it, so
 * editing a page by hand (or a schedule growing a week) fails CI until this
 * is re-run.
 *
 *   node scripts/share-cards.mjs            # pages only
 *   node scripts/share-cards.mjs --images   # pages + images
 *
 * Images render the HTML template below in headless Chromium with Poppins
 * vendored under scripts/share-cards/fonts (OFL), so they are reproducible
 * offline. If `playwright` is not resolvable from this repo, point
 * PLAYWRIGHT_MODULE at an install and CHROMIUM_PATH at a browser binary.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { dirname, join } from 'node:path'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'

import { buildScheduleFromCsv } from '../src/lib/scheduleModel.js'
import { PROGRAMS, PROGRAM_IDS } from '../src/lib/programs.js'

const ROOT = fileURLToPath(new URL('..', import.meta.url))

// Mirrors src/lib/appUrl.js. Absolute on purpose: a crawler cannot resolve a
// relative og:image or og:url (see the note in index.html).
export const APP_URL = 'https://alxdataprograms.github.io/alx-pace/'

export const IMAGE_WIDTH = 1200
export const IMAGE_HEIGHT = 627

const NAMES = { da: 'Data Analytics', cc: 'Content Creation', gd: 'Graphic Design' }
const FAMILY = { 'data-analytics': 'Self-Paced', 'creative-tech': 'Creative Tech' }

function weeksOf(id) {
  const p = PROGRAMS[id]
  const csv = readFileSync(join(ROOT, 'src/data', p.csv), 'utf8')
  return buildScheduleFromCsv(csv, { layout: p.layout }).totalWeeks
}

/** Everything a program's card says, derived from the registry and its sheet. */
export function shareCard(id) {
  const name = NAMES[id]
  const weeks = weeksOf(id)
  const url = `${APP_URL}share/${id}/`
  return {
    id,
    name,
    weeks,
    url,
    image: `${url}og-image.png`,
    subtitle: `${name} · ${FAMILY[PROGRAMS[id].family]}`,
    title: `ALX Pace — ${name}, paced week by week`,
    description: `A week-by-week pace tracker for the ALX ${weeks}-week ${name} self-paced track. No login, works offline, and your progress never leaves your device.`,
    shortDescription: `A week-by-week pace tracker for the ALX ${weeks}-week ${name} self-paced track. No login, works offline.`,
    imageAlt: `ALX Pace — ${name}: ${weeks} weeks, paced week by week. No login. Works offline.`,
    bandLead: `${weeks} weeks, paced week by week.`,
    bandSub: 'No login. Works offline. Your progress stays on your device.',
  }
}

/** The program-neutral card on the app root (public/og-image.png). */
export const ROOT_CARD = {
  id: null,
  subtitle: 'Self-Paced Programmes',
  bandLead: 'Data Analytics · Content Creation · Graphic Design',
  bandSub: 'Paced week by week. No login. Works offline.',
}

export const SHARE_CARDS = PROGRAM_IDS.map(shareCard)

const esc = (s) =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

/*
  The redirect is relative (../../ from share/<id>/), so it lands on the app
  root wherever the build is served — /alx-pace/ on Pages, / in local preview.

  JavaScript redirects at once; crawlers never run it. The meta refresh is the
  fallback for a browser with JavaScript off, and waits two seconds because
  some crawlers do follow an instant refresh, and would then read the app
  root's program-neutral card instead of this one. The visible link covers
  everything else.
*/
